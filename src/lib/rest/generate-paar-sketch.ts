import type { RestServiceMapping } from "./types";

/** Human-readable .paar contents sketch (not a binary Progress package). */
export function generatePaarSketch(mapping: RestServiceMapping): string {
  const rows = mapping.operations
    .map(
      (op) =>
        `| ${op.method} | ${op.uri} | ${op.target}.${op.operation} |`
    )
    .join("\n");

  return `# Classic \`.paar\` catalog sketch (${mapping.serviceName})

Generated by jabl. A real \`.paar\` is a Progress package; this is a readable map.

## Service
- Name: \`${mapping.serviceName}\`
- Base: \`${mapping.basePath}\`
- Version: \`${mapping.version || "1.0.0"}\`

## Resources
| Verb | URI | ABL target |
|------|-----|------------|
${rows || "| — | — | — |"}

## Next steps
1. Copy \`resourceModel.xml\` / \`catalog.json\` into a PDSOE REST project (or keep as source of truth).
2. Run Ant \`PaarGeneration\` with \`DLC\` to produce a binary \`.paar\`.
3. Deploy to PASOE **REST** transport.

For new APIs prefer PASOE **WEB** (WebHandler / DataObjectHandler).
`;
}
