export const ABL_EXTENSIONS = [".p", ".w", ".i", ".cls", ".df", ".abl"] as const;

export function isAblFile(path: string): boolean {
  const lower = path.toLowerCase();
  return ABL_EXTENSIONS.some((ext) => lower.endsWith(ext));
}
