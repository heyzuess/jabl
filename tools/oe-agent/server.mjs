#!/usr/bin/env node
/**
 * Local OpenEdge agent — writes a workspace snapshot and invokes batch Progress.
 * Requires DLC pointing at an OpenEdge install. Listens on 127.0.0.1:43128.
 */

import http from "node:http";
import fs from "node:fs/promises";
import fsSync from "node:fs";
import path from "node:path";
import os from "node:os";
import { spawn } from "node:child_process";

const HOST = process.env.OE_AGENT_HOST || "127.0.0.1";
const PORT = Number(process.env.OE_AGENT_PORT || 43128);

function json(res, status, body) {
  const data = JSON.stringify(body);
  res.writeHead(status, {
    "Content-Type": "application/json; charset=utf-8",
    "Content-Length": Buffer.byteLength(data),
  });
  res.end(data);
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    req.on("data", (c) => chunks.push(c));
    req.on("end", () => {
      try {
        const raw = Buffer.concat(chunks).toString("utf8");
        resolve(raw ? JSON.parse(raw) : {});
      } catch (err) {
        reject(err);
      }
    });
    req.on("error", reject);
  });
}

function findProgres(dlc) {
  const candidates = [
    path.join(dlc, "bin", "_progres"),
    path.join(dlc, "bin", "_progres.exe"),
    path.join(dlc, "bin", "prowin"),
    path.join(dlc, "bin", "prowin.exe"),
    path.join(dlc, "bin", "bpro"),
    path.join(dlc, "bin", "bpro.exe"),
  ];
  for (const c of candidates) {
    if (fsSync.existsSync(c)) return c;
  }
  return null;
}

function sanitizeRel(rel) {
  const normalized = rel.replace(/\\/g, "/").replace(/^\/+/, "");
  if (
    !normalized ||
    normalized.includes("..") ||
    path.isAbsolute(normalized)
  ) {
    throw new Error(`Unsafe path: ${rel}`);
  }
  return normalized;
}

async function writeWorkspace(files) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "jabl-oe-"));
  for (const [rel, content] of Object.entries(files || {})) {
    const safe = sanitizeRel(rel);
    const full = path.join(root, safe);
    await fs.mkdir(path.dirname(full), { recursive: true });
    await fs.writeFile(full, content ?? "", "utf8");
  }
  return root;
}

function escapeAblString(s) {
  return String(s).replace(/~/g, "~~").replace(/"/g, '~"');
}

function buildWrapper(mode, entry) {
  const safeEntry = escapeAblString(entry);
  const doRun = mode === "run";
  return `/* Generated by JABL OE agent — do not edit */
DEFINE VARIABLE cEntry AS CHARACTER NO-UNDO.
DEFINE VARIABLE lOk AS LOGICAL NO-UNDO.
cEntry = "${safeEntry}".
COMPILE VALUE(cEntry) SAVE NO-ERROR.
lOk = NOT COMPILER:ERROR.
IF COMPILER:ERROR OR COMPILER:WARNING THEN DO:
  MESSAGE "COMPILE" COMPILER:FILE-NAME COMPILER:ERROR-ROW COMPILER:ERROR-COLUMN COMPILER:GET-MESSAGE(1).
END.
IF NOT lOk THEN DO:
  QUIT(1).
END.
${
  doRun
    ? `RUN VALUE(cEntry) NO-ERROR.
IF ERROR-STATUS:ERROR THEN DO:
  MESSAGE "RUN-ERROR" ERROR-STATUS:GET-MESSAGE(1).
  QUIT(1).
END.`
    : ""
}
QUIT(0).
`;
}

function parseCompileMessages(stdout, stderr) {
  const text = `${stdout}\n${stderr}`;
  const messages = [];
  const re =
    /(?:\*\*\s+)?([^\s:]+\.(?:p|w|i|cls|r))\s+.*?line\s+(\d+)(?:.*?column\s+(\d+))?.*?(?:\((\d+)\))?/gi;
  let m;
  while ((m = re.exec(text)) !== null) {
    messages.push({
      file: m[1].replace(/\\/g, "/"),
      line: Number(m[2]),
      column: m[3] ? Number(m[3]) : 1,
      severity: "error",
      message: m[0].trim(),
    });
  }
  // COMPILER MESSAGE lines from wrapper
  const msgRe =
    /COMPILE\s+(\S+)\s+(\d+)\s+(\d+)\s+(.+)/g;
  while ((m = msgRe.exec(text)) !== null) {
    messages.push({
      file: m[1].replace(/\\/g, "/"),
      line: Number(m[2]),
      column: Number(m[3]),
      severity: "error",
      message: m[4].trim(),
    });
  }
  return messages;
}

function runProcess(bin, args, cwd, env) {
  return new Promise((resolve) => {
    const child = spawn(bin, args, {
      cwd,
      env,
      windowsHide: true,
    });
    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (d) => {
      stdout += d.toString("utf8");
    });
    child.stderr.on("data", (d) => {
      stderr += d.toString("utf8");
    });
    child.on("error", (err) => {
      resolve({
        exitCode: 1,
        stdout,
        stderr: `${stderr}\n${err.message}`.trim(),
      });
    });
    child.on("close", (code) => {
      resolve({ exitCode: code ?? 1, stdout, stderr });
    });
  });
}

async function handleRun(body) {
  const mode = body.mode === "run" ? "run" : "compile";
  const entry = typeof body.entry === "string" ? body.entry : "";
  const files = body.files && typeof body.files === "object" ? body.files : null;

  if (!entry || !files) {
    return {
      status: 400,
      body: {
        ok: false,
        exitCode: 1,
        stdout: "",
        stderr: "",
        compileMessages: [],
        error: "Request requires mode, entry, and files",
      },
    };
  }

  const dlc = process.env.DLC;
  if (!dlc) {
    return {
      status: 503,
      body: {
        ok: false,
        exitCode: 1,
        stdout: "",
        stderr: "",
        compileMessages: [],
        error:
          "OpenEdge not installed / DLC unset. Set the DLC environment variable to your OpenEdge install and restart the OE agent.",
      },
    };
  }

  const bin = findProgres(dlc);
  if (!bin) {
    return {
      status: 503,
      body: {
        ok: false,
        exitCode: 1,
        stdout: "",
        stderr: "",
        compileMessages: [],
        error: `OpenEdge binaries not found under DLC (${dlc}). Expected bin/_progres or bin/bpro.`,
      },
    };
  }

  let workRoot;
  try {
    workRoot = await writeWorkspace(files);
    const wrapperName = "__jabl_oe_wrapper.p";
    const wrapperPath = path.join(workRoot, wrapperName);
    await fs.writeFile(wrapperPath, buildWrapper(mode, sanitizeRel(entry)), "utf8");

    const propathParts = [
      workRoot,
      ...(Array.isArray(body.propath) ? body.propath.map((p) => path.join(workRoot, sanitizeRel(p))) : []),
      path.join(dlc, "tty"),
      path.join(dlc, "gui"),
    ];
    const propath = propathParts.join(path.delimiter);

    const env = {
      ...process.env,
      DLC: dlc,
      PROPATH: propath,
    };

    const args = ["-b", "-p", wrapperName];
    const result = await runProcess(bin, args, workRoot, env);
    const compileMessages = parseCompileMessages(result.stdout, result.stderr);
    const ok = result.exitCode === 0;

    return {
      status: ok ? 200 : 200,
      body: {
        ok,
        exitCode: result.exitCode,
        stdout: result.stdout,
        stderr: result.stderr,
        compileMessages,
        error: ok
          ? undefined
          : compileMessages[0]?.message ||
            result.stderr.trim() ||
            `OpenEdge exited with code ${result.exitCode}`,
      },
    };
  } catch (err) {
    return {
      status: 500,
      body: {
        ok: false,
        exitCode: 1,
        stdout: "",
        stderr: "",
        compileMessages: [],
        error: (err && err.message) || String(err),
      },
    };
  } finally {
    if (workRoot) {
      fs.rm(workRoot, { recursive: true, force: true }).catch(() => {});
    }
  }
}

const server = http.createServer(async (req, res) => {
  // CORS for local IDE
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "GET, POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");

  if (req.method === "OPTIONS") {
    res.writeHead(204);
    res.end();
    return;
  }

  if (req.method === "GET" && (req.url === "/" || req.url === "/health")) {
    json(res, 200, {
      ok: true,
      service: "jabl-oe-agent",
      dlc: !!process.env.DLC,
      port: PORT,
    });
    return;
  }

  if (req.method === "POST" && req.url === "/run") {
    try {
      const body = await readBody(req);
      const result = await handleRun(body);
      json(res, result.status, result.body);
    } catch (err) {
      json(res, 400, {
        ok: false,
        exitCode: 1,
        stdout: "",
        stderr: "",
        compileMessages: [],
        error: (err && err.message) || "Invalid JSON body",
      });
    }
    return;
  }

  json(res, 404, {
    ok: false,
    exitCode: 1,
    stdout: "",
    stderr: "",
    compileMessages: [],
    error: "Not found",
  });
});

server.listen(PORT, HOST, () => {
  console.log(
    `JABL OE agent listening on http://${HOST}:${PORT} (DLC=${process.env.DLC || "unset"})`
  );
});
